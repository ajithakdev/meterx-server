/**
 * Regenerates the file table in docs/CODEMAP.md: every source file with its line count, exports and doc line.
 * Run after moving or adding files: node scripts/codemap.mjs
 * @license AGPL-3.0
 */

import { execFileSync } from 'child_process';
import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tracked = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' }).split('\n');
const files = tracked.filter(f => /^(apps\/\w+\/(src\/|build\.mjs)|services\/\w+\/src\/|packages\/\w+\/src\/|brand\/build\.mjs|scripts\/)/.test(f)
    && /\.(ts|mjs)$/.test(f) && !/\.test\.(ts|mjs)$/.test(f));

const rows = files.map(f => {
    const src = readFileSync(resolve(root, f), 'utf8');
    const lines = src.split('\n').length;
    const exports = [...src.matchAll(/^export (?:async )?(?:function|const|class|interface|type) (\w+)/gm)].map(m => m[1]);
    const doc = src.match(/^\/\*\*\s*\n\s*\*\s*(.+)/)?.[1]?.trim() ?? '';
    return `| \`${f}\` (${lines}) | ${exports.slice(0, 6).map(e => `\`${e}\``).join(', ') || '-'} | ${doc.replace(/\|/g, '/')} |`;
});

const tests = tracked.filter(f => /\.test\.(ts|mjs)$/.test(f));
const head = readFileSync(resolve(root, 'docs/CODEMAP.md'), 'utf8').split('\n## Files')[0];
writeFileSync(resolve(root, 'docs/CODEMAP.md'), `${head}
## Files

Generated by \`node scripts/codemap.mjs\`; regenerate after moving or adding files. Numbers are line counts.

| File | Exports | What it does |
| --- | --- | --- |
${rows.join('\n')}

## Tests

${tests.map(t => `- \`${t}\``).join('\n')}
`);
console.log(`CODEMAP: ${rows.length} files, ${tests.length} test files`);
